def learner_scorecard(summary_df, filename=None):
    scorecard = summary_df.copy()

    scorecard["score_precision"] = 1 - (
        (scorecard["mean_se"] - scorecard["mean_se"].min()) /
        (scorecard["mean_se"].max() - scorecard["mean_se"].min() + 1e-12)
    )
    scorecard["score_t"] = (
        (scorecard["mean_abs_t"] - scorecard["mean_abs_t"].min()) /
        (scorecard["mean_abs_t"].max() - scorecard["mean_abs_t"].min() + 1e-12)
    )
    scorecard["score_sig05"] = (
        (scorecard["sig_05_rate"] - scorecard["sig_05_rate"].min()) /
        (scorecard["sig_05_rate"].max() - scorecard["sig_05_rate"].min() + 1e-12)
    )
    scorecard["score_ci"] = 1 - (
        (scorecard["mean_ci_width"] - scorecard["mean_ci_width"].min()) /
        (scorecard["mean_ci_width"].max() - scorecard["mean_ci_width"].min() + 1e-12)
    )

    scorecard["overall_score"] = (
        0.35 * scorecard["score_precision"] +
        0.35 * scorecard["score_t"] +
        0.20 * scorecard["score_sig05"] +
        0.10 * scorecard["score_ci"]
    )

    scorecard = scorecard.sort_values("overall_score", ascending=False)

    plt.figure(figsize=(10, 5))
    sns.barplot(data=scorecard, x="Learner", y="overall_score")
    plt.title("Composite learner scorecard for DML inference")
    plt.ylabel("Higher = better")
    plt.tight_layout()

    if filename:
        savefig(filename)
    plt.show()

    print("\n=== LEARNER SCORECARD ===")
    print(scorecard[["Learner", "overall_score", "mean_se", "mean_abs_t", "sig_05_rate"]].round(4))

    return scorecard


# 4. RESIDUALIZATION FUNCTION
def get_residuals(target_cols, predictor_cols, data):
    X = data[predictor_cols].copy()
    X.insert(0, 'Intercept', 1.0)

    Y = data[target_cols]

    try:
        X_mat = X.values
        Y_mat = Y.values

        XtX = X_mat.T @ X_mat
        XtY = X_mat.T @ Y_mat

        beta = np.linalg.solve(XtX, XtY)
        preds = X_mat @ beta

        if len(target_cols) == 1:
            return Y.iloc[:, 0] - preds.flatten()
        else:
            return pd.DataFrame(Y_mat - preds, columns=target_cols, index=data.index)

    except np.linalg.LinAlgError:
        print(f"[ERROR] Singular matrix for target: {target_cols}")
        return None
    except Exception as e:
        print(f"[ERROR] Unexpected error for {target_cols}: {e}")
        return None


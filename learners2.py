def forest_plot_by_outcome(data, control_spec, outcomes=None, learners=None, figsize=(13, 10), filename=None):
    plot_df = data.copy()
    plot_df = plot_df[plot_df["Control_Spec"] == control_spec]

    if outcomes is not None:
        plot_df = plot_df[plot_df["Outcome"].isin(outcomes)]
    if learners is not None:
        plot_df = plot_df[plot_df["Learner"].isin(learners)]

    plot_df = plot_df.sort_values(["Outcome", "Learner"]).reset_index(drop=True)

    y_positions = []
    y_labels = []
    current_y = 0
    gap = 1.2
    rows = []

    outcomes_iter = [o for o in outcome_order if o in plot_df["Outcome"].astype(str).unique()]
    for outcome in outcomes_iter:
        sub = plot_df[plot_df["Outcome"].astype(str) == outcome]
        if sub.empty:
            continue
        for _, r in sub.iterrows():
            rows.append((current_y, r))
            y_labels.append(f"{outcome} | {r['Learner']}")
            y_positions.append(current_y)
            current_y += 1
        current_y += gap

    fig, ax = plt.subplots(figsize=figsize)

    for y, r in rows:
        color = colors.get(str(r["Learner"]), "black")
        ax.plot([r["CI_2.5"], r["CI_97.5"]], [y, y], color=color, lw=2)

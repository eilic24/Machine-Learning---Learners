def get_residuals(target_cols, predictor_cols, data):
    try:
        X = data[predictor_cols].to_numpy(dtype=np.float64, copy=False)
        intercept = np.ones((X.shape[0], 1), dtype=np.float64)
        X = np.hstack([intercept, X])

        Y = data[target_cols].to_numpy(dtype=np.float64, copy=False)

        beta = np.linalg.lstsq(X, Y, rcond=None)[0]
        preds = X @ beta
        resid = Y - preds

        if len(target_cols) == 1:
            return pd.Series(resid[:, 0], index=data.index)
        else:
            return pd.DataFrame(resid, columns=target_cols, index=data.index)

    except np.linalg.LinAlgError:
        print(f"[ERROR] Singular matrix for target: {target_cols}")
        return None
    except Exception as e:
        print(f"[ERROR] Unexpected error for {target_cols}: {e}")
        return None


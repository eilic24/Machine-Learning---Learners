# 7. PREDICTION COMPARISON FUNCTION
def compare_treatment_predictors(X, d, learners, n_splits=5, n_repeats=3):
    cv = RepeatedKFold(n_splits=n_splits, n_repeats=n_repeats, random_state=12345)
    rows = []

    scoring = {
        "r2": "r2",
        "neg_rmse": "neg_root_mean_squared_error",
        "neg_mse": "neg_mean_squared_error"
    }

    for name, model in learners.items():
        try:
            res = cross_validate(
                clone(model),
                X,
                d,
                cv=cv,
                scoring=scoring,
                n_jobs=-1,
                error_score="raise"
            )

            rows.append({
                "learner": name,
                "mean_r2": np.mean(res["test_r2"]),
                "sd_r2": np.std(res["test_r2"]),
                "mean_rmse": -np.mean(res["test_neg_rmse"]),
                "sd_rmse": np.std(-res["test_neg_rmse"]),
                "mean_mse": -np.mean(res["test_neg_mse"])
            })
        except Exception as e:
            rows.append({
                "learner": name,
                "mean_r2": np.nan,
                "sd_r2": np.nan,
                "mean_rmse": np.nan,
                "sd_rmse": np.nan,
                "mean_mse": np.nan,
                "error": str(e)
            })

    out = pd.DataFrame(rows).sort_values(["mean_r2", "mean_rmse"], ascending=[False, True])
    return out


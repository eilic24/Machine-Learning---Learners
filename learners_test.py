# Helper Function - residualization. Note: we are running a partial linear equation, not full non-linear equation.
def get_residuals(target_cols, predictor_cols, data):
    # Prepare X with an explicit intercept to match OLS behavior
    X = data[predictor_cols].copy()
    X.insert(0, 'Intercept', 1.0)

    Y = data[target_cols]

    try:
        # Convert to numpy for the linear algebra solver
        X_mat = X.values
        Y_mat = Y.values

        # Calculate X^T X and X^T Y
        XtX = X_mat.T @ X_mat
        XtY = X_mat.T @ Y_mat

        # Solve (X^T X) * beta = X^T Y (Avoids direct inversion for better stability)
        beta = np.linalg.solve(XtX, XtY)

        # Calculate predictions
        preds = X_mat @ beta

        # Return residuals while perfectly preserving the Pandas index
        if len(target_cols) == 1:
            return Y.iloc[:, 0] - preds.flatten()
        else:
            return pd.DataFrame(Y_mat - preds, columns=target_cols, index=data.index)

    except np.linalg.LinAlgError:
        print(f"    [ERROR] Singular matrix for target: {target_cols}. Perfect multicollinearity detected.")
        return None
    except Exception as e:
        print(f"    [ERROR] Unexpected error for {target_cols}: {e}")
        return None


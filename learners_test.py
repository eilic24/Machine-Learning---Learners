def get_cv_metrics(model, X, y, n_splits=5, seed=123):
    cv = KFold(n_splits=n_splits, shuffle=True, random_state=seed)
    preds = cross_val_predict(clone(model), X, y, cv=cv, n_jobs=-1)

    rmse = np.sqrt(mean_squared_error(y, preds))
    mae = mean_absolute_error(y, preds)
    r2 = r2_score(y, preds)

    return {
        'rmse': rmse,
        'mae': mae,
        'r2': r2
    }

